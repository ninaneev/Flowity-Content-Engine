-- Flowity Content Engine: armazenamento de slides editáveis por post.
-- Execute no SQL Editor do Supabase após confirmar o schema de public.posts.
-- A tabela public.posts deve ter id, hook, body e cta.

begin;

create table if not exists public.carousel_slides (
  id bigint generated by default as identity primary key,
  post_id integer not null references public.posts(id) on delete cascade,
  position integer not null check (position between 1 and 10),
  slide_text varchar(220) not null check (length(trim(slide_text)) > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint carousel_slides_post_position_unique unique (post_id, position)
);

create index if not exists idx_carousel_slides_post_position
  on public.carousel_slides (post_id, position);

create or replace function public.touch_carousel_slide_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_carousel_slides_updated_at on public.carousel_slides;
create trigger trg_carousel_slides_updated_at
before update on public.carousel_slides
for each row execute function public.touch_carousel_slide_updated_at();

create or replace function public.sync_initial_carousel_slides(p_post_id integer)
returns void
language plpgsql
as $$
declare
  v_post public.posts%rowtype;
begin
  select * into v_post from public.posts where id = p_post_id;
  if not found then
    return;
  end if;

  insert into public.carousel_slides (post_id, position, slide_text)
  values
    (v_post.id, 1, left(coalesce(nullif(trim(v_post.hook), ''), 'Título do carrossel'), 220)),
    (v_post.id, 2, left(coalesce(nullif(trim(v_post.body), ''), 'Adicione o conteúdo deste slide.'), 220)),
    (v_post.id, 3, left(coalesce(nullif(trim(v_post.cta), ''), 'Qual é a sua opinião?'), 220))
  on conflict (post_id, position) do nothing;
end;
$$;

-- Inicializa posts já existentes sem sobrescrever slides existentes.
do $$
declare
  v_post_id integer;
begin
  for v_post_id in select id from public.posts order by id loop
    perform public.sync_initial_carousel_slides(v_post_id);
  end loop;
end;
$$;

-- Cria 3 slides iniciais para novos posts.
create or replace function public.create_initial_carousel_slides_trigger()
returns trigger
language plpgsql
as $$
begin
  perform public.sync_initial_carousel_slides(new.id);
  return new;
end;
$$;

drop trigger if exists trg_posts_create_carousel_slides on public.posts;
create trigger trg_posts_create_carousel_slides
after insert on public.posts
for each row execute function public.create_initial_carousel_slides_trigger();

commit;

